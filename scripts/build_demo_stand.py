"""Собирает страницу смен по слотам для демонстрационного набора.

Сама сборка живёт в сервисе: ту же страницу он строит и по данным пользователя
после прогона. Здесь только источники демонстрации.
"""

import json
import logging
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / "src"))

from report_stand import StandBuilder, StandSources  # noqa: E402

logging.basicConfig(level=logging.INFO, format="%(message)s")
logger = logging.getLogger(__name__)

TIMELINES_PATH = Path("data/cache/shift_timelines.json")
OBSERVATIONS_PATH = Path("data/cache/shift_observations.json")
SUMMARY_PATH = Path("data/cache/plan_fact_summary.json")
SLOT_PHOTOS_DIR = Path("data/photos_slots")
PLAN_PATH = Path("config/calendar_plan_new.json")
OUTPUT_DIR = Path("docs/stand")
PHOTO_URL_PREFIX = "/demo/photos/"

ABOUT_HTML = """
<h2>Что мы строим</h2>
<p>Демонстрационный проект <b>EDU-DEMO-001</b> — образовательная организация (школа) с одним
подземным этажом. Направление «Образование» по справочнику видов работ ЛТЦ: в набор попали
только те работы, которые в справочнике отмечены для этого направления.</p>
<p>Календарный план линейный: этапы не перекрываются, на каждую дату приходится ровно один
вид работ, поэтому любой снимок однозначно привязывается к пункту плана. Всего 7 пунктов
и 294 дня, с 5 октября 2026 по 25 июля 2027 года.</p>

<h3>Смена, отрезок и как считается процент</h3>
<p>Камера присылает снимок раз в двадцать минут. <b>Смена</b> — рабочий день одного вида работ,
разбитый на такие двадцатиминутные <b>отрезки</b>: три часа работ — девять отрезков.
Выполнение считается отрезками: подтверждённые к тем, которые удалось измерить. Из измеренного
объёма выпадают два случая — отрезок, на который снимка не пришло, и отрезок, где фронт работ
не виден. Оба говорят о съёмке, а не о работе подрядчика, и в отставание не пишутся.</p>
<p>Отрезок засчитан, когда сошлись три условия: на кадре есть тот, кто делает работу, за смену
появилась дополнительная машина, и между этим и прошлым кадром работа подтверждена сравнением
пары снимков. У первого кадра смены сравнивать не с чем, поэтому там довольно двух условий.</p>

<h3>Роли в правилах вида работ</h3>
<p><b>Главная машина</b> делает саму работу: погрузчик грузит, буровая бурит, кран подаёт
конструкции. <b>Дополнительные машины</b> работают при ней, и без них работа не идёт: самосвал
под погрузчиком, подача бетона под краном. Их достаточно увидеть один раз за смену — цикличная
техника вроде самосвала в каждый кадр не попадает.</p>
<p><b>Допустимая техника</b> — прицеп, бульдозер, лишний экскаватор: на площадке бывает,
отклонением не считается, но и комплект не закрывает. <b>Признак работ</b> — не машина,
а состояние объекта: опалубка плиты, каркас этажа, облицовка фасада. <b>Люди на фронте работ</b>
считаются наравне с главной машиной: арматуру вяжут и опалубку ставят руками, и техника при
этом может простаивать.</p>
<p>Источник признака — либо <b>детектор</b> (рамка на снимке и скор, каждую рамку проверяет
арбитр по вырезке крупным планом), либо <b>модель</b> (ответ на прямой вопрос с обоснованием),
если такого класса в детекторе нет. Ответ модели по кадру целиком идёт и по машинам детектора —
это резерв на случай его промаха, и засчитывается он, только когда рамками не подтверждено
ничего.</p>

<h3>Когда ИИ отказывается судить</h3>
<p>Часть кадров разобрать нельзя: камера снимает в упор, смотрит мимо фронта работ или кадр
пришёл с другого ракурса. Такой отрезок помечается <b>вне контроля ИИ</b>: он не засчитывается,
но и в отставание подрядчику не пишется — снимок уходит на ручную проверку.</p>
<p>Чужой ракурс определяется без моделей, по самим файлам: камера стоит неподвижно, и снимок,
который сильно расходится с общей сценой смены, снят не оттуда. Проверка даёт один и тот же
ответ при каждом прогоне, в отличие от ответа модели, который от прогона к прогону гуляет.</p>

<h3>Что важно знать о данных</h3>
<p>Снимки взяты из архива заказчика. Даты съёмки назначены внутри периода своего этапа:
исходные штампы на кадрах относятся к разным объектам и, как отмечено в материалах заказчика,
не являются датами демонстрационного проекта. Дата съёмки записана в EXIF каждого файла.</p>
<p>Серия смены собрана из одного настоящего кадра этапа и его вариантов, а в последний отрезок
каждой смены намеренно подложен негодный снимок — на них и проверяется отметка «вне контроля
ИИ». Это реконструкция двадцатиминутной сетки, а не настоящая съёмка одной камерой: проценты
показывают работу механики, а не состояние реального объекта.</p>
<p>Порог уверенности детектора — 0.05. Модель отдаёт низкие абсолютные скоры: в эталонных
прогонах авторов весов верные находки подписаны 0.05–0.10, при пороге 0.3 не находится ничего.
Классы Roller и Motor grader в правилах не используются: на обучении каток дал mAP 0.002.</p>
"""


def work_names() -> dict[str, str]:
    """Читает названия видов работ из календарного плана."""
    plan = json.loads(PLAN_PATH.read_text(encoding="utf-8"))
    names = {str(stage["work_id"]): str(stage["full_name"]) for stage in plan["stages"]}
    return names


def main() -> int:
    """Собирает демонстрационную страницу смен."""
    sources = StandSources(
        timelines_path=TIMELINES_PATH,
        observations_path=OBSERVATIONS_PATH,
        photos_dir=SLOT_PHOTOS_DIR,
        titles=work_names(),
        output_dir=OUTPUT_DIR,
        photo_url_prefix=PHOTO_URL_PREFIX,
        photos_by_work=True,
        summary_path=SUMMARY_PATH,
        about_html=ABOUT_HTML,
    )
    target = StandBuilder(sources).build()
    size_mb = target.stat().st_size / 1024 / 1024
    logger.info("Стенд собран: %s (%.1f МБ)", target, size_mb)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
